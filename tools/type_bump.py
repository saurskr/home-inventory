#!/usr/bin/env python3
"""Make every font size in a set of CSS files bigger (or smaller) without editing them.

    python3 tools/type_bump.py                       # static/ds/**/*.css  ->  static/type-bump.css  (+1px)
    python3 tools/type_bump.py --step 2              # two sizes up
    python3 tools/type_bump.py --step 0 -o static/type-bump.css   # no change (empty overrides)

The design-system files in static/ds/ are a vendored copy and stay pristine. This writes a separate stylesheet
that repeats each rule that sets a font size, with the size changed by --step px. Load it after the design-system
CSS. Re-run it whenever static/ds/ is re-copied. Standard library only.
"""
import argparse
import glob
import os
import re
import sys

NESTING = ("@media", "@supports", "@container", "@layer")


def _blocks(css):
    """Yield (prelude, body) for each top-level block, respecting braces, strings and comments."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            return
        prelude, depth, k, quote = css[i:j].strip(), 1, j + 1, None
        while k < n and depth:
            c = css[k]
            if quote:
                if c == "\\":
                    k += 1
                elif c == quote:
                    quote = None
            elif c in "\"'":
                quote = c
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def _declarations(body):
    out, depth, cur = [], 0, ""
    for c in body:
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if c == ";" and not depth:
            out.append(cur)
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur)
    return out


def _num(x):
    return ("%g" % round(x, 2))


def _bumped(prop, value, step):
    """New value for a font-size / font declaration, or None when it does not set a px size."""
    v = value.strip()
    imp = ""
    if v.endswith("!important"):
        v, imp = v[:-10].strip(), " !important"
    if prop == "font-size":
        m = re.fullmatch(r"([\d.]+)px", v)
        return _num(float(m.group(1)) + step) + "px" + imp if m else None
    if prop == "font":
        m = re.match(r"^((?:[\w-]+\s+)*)([\d.]+)px(\s*/\s*[\w.%]+)?(.*)$", v, re.S)   # [style weight ...] SIZE[/line-height] family
        if m:
            return m.group(1) + _num(float(m.group(2)) + step) + "px" + (m.group(3) or "") + m.group(4) + imp
    return None


def bump_css(css, step=1, indent=""):
    """Override rules (as CSS text) that change every px font size in `css` by `step` px."""
    out = []
    for prelude, body in _blocks(css):
        if prelude.lower().startswith(NESTING):
            inner = bump_css(body, step, indent + "  ")
            if inner.strip():
                out.append("%s%s {\n%s%s}\n" % (indent, prelude, inner, indent))
        elif prelude.startswith("@"):
            continue   # @keyframes, @font-face ...
        else:
            decls = []
            for d in _declarations(body):
                if ":" not in d:
                    continue
                prop, value = d.split(":", 1)
                new = _bumped(prop.strip().lower(), value, step)
                if new:
                    decls.append("%s: %s" % (prop.strip(), new))
            if decls:
                out.append("%s%s { %s; }\n" % (indent, re.sub(r"\s+", " ", prelude), "; ".join(decls)))
    return "".join(out)


def build(src_dir, step):
    parts = ["/* Generated by tools/type_bump.py (step %+g px). Do not edit; re-run the script after updating static/ds/. */\n" % step]
    for path in sorted(glob.glob(os.path.join(src_dir, "**", "*.css"), recursive=True)):
        rules = bump_css(open(path, encoding="utf-8").read(), step)
        if rules:
            parts.append("\n/* %s */\n%s" % (os.path.relpath(path, src_dir).replace(os.sep, "/"), rules))
    return "".join(parts)


def main(argv=None):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", default=os.path.join(root, "static", "ds"), help="folder of CSS files (default: static/ds)")
    ap.add_argument("-o", "--out", default=os.path.join(root, "static", "type-bump.css"))
    ap.add_argument("--step", type=float, default=1.0, help="px to add to every font size (default 1)")
    a = ap.parse_args(argv)
    text = build(a.src, a.step)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d rules)" % (os.path.relpath(a.out, root), text.count("{") ))
    return 0


if __name__ == "__main__":
    sys.exit(main())
